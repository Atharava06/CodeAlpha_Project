// Helper lookup map
export const LANGUAGE_MAP = SUPPORTED_LANGUAGES.reduce((acc, lang) => {
  acc[lang.code] = lang;
  return acc;
}, {});

// Validate language code
export function isValidLanguageCode(code, isSource = false) {
  if (isSource && code === 'auto') return true;
  return Boolean(LANGUAGE_MAP[code] && !LANGUAGE_MAP[code].isSourceOnly);
}
